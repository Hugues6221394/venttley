import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const compile=async name=>ts.transpileModule(await readFile(new URL(`../lib/${name}.ts`,import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const url=js=>`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`;
const model=await import(url((await compile('incident-model')).replaceAll("'./inbox-model'",JSON.stringify(url(await compile('inbox-model'))))));
const id='00000000-0000-4000-8000-000000000001';
assert.deepEqual(model.incidentFilters(new URLSearchParams()),{filter:'active',severity:'all',at:null,id:null});
for(const q of ['filter=unknown','severity=sev0','beforeAt=infinity&beforeId='+id,'beforeId='+id,'beforeAt=2026-01-01'])assert.equal(model.incidentFilters(new URLSearchParams(q)),null);
const cursor={incident_id:id,created_at:'2026-01-01T00:00:00Z'};
const href=model.incidentHref({filter:'mine',severity:'sev2'},cursor),q=new URL(href,'https://example.test').searchParams;
assert.equal(q.get('beforeId'),id);assert.equal(q.get('beforeAt'),cursor.created_at);
assert.equal(model.incidentFilters(q).filter,'mine');
assert.deepEqual(model.incidentTransitions.reviewed,[]);
assert.deepEqual(model.incidentTransitions.declared,['investigating']);
assert(model.incidentTransitions.monitoring.includes('investigating'));
assert(!model.incidentTransitions.declared.includes('resolved'));
assert.equal(model.incidentTime('2026-01-01T02:30:00+02:00'),'2026-01-01 00:30 UTC');
assert(!model.incidentSignals.includes('csam-open'));
assert(Object.values(model.incidentRunbooks).every(path=>path.startsWith('/')&&!path.startsWith('//')));
console.log('check:incidents — filters, cursors, lifecycle choices, UTC and restricted signal boundaries passed');
