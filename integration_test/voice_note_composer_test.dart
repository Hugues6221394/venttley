// The voice-note composer, on a device, with FFmpeg actually running.
//
// The code-shape guards in test/voice_filter_in_chat_test.dart prove the
// composed bytes are what gets uploaded. They cannot prove the composer works:
// the filters run through ffmpeg_kit, which is a platform plugin and does
// nothing at all under `flutter test`. So a filter table could be perfectly
// wired to a processor that fails on every clip and the suite would stay
// green — which is precisely how "Soft sounds identical to Original" survived.
//
//   flutter test integration_test/voice_note_composer_test.dart -d <sim-id>

import 'dart:io';
import 'dart:typed_data';

import 'package:ffmpeg_kit_flutter_new_audio/ffmpeg_kit.dart';
import 'package:ffmpeg_kit_flutter_new_audio/return_code.dart';
import 'package:flutter/material.dart';
import 'package:path_provider/path_provider.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:vently_app/data/services/whisper_voice_processor.dart';
import 'package:vently_app/domain/entities/entities.dart';
import 'package:vently_app/presentation/widgets/voice_note_composer.dart';

/// A second of tone as AAC in an MP4 container.
///
/// Generated by ffmpeg rather than committed as a fixture, so it is encoded by
/// exactly the pipeline the recorder's output goes through — and a tone rather
/// than silence, because several of these filters are pitch shifts and
/// silence shifted is still silence.
Future<Uint8List> _sampleClip() async {
  final dir = await getTemporaryDirectory();
  final out = File('${dir.path}/vn-test-source.m4a');
  final session = await FFmpegKit.execute(
    '-y -f lavfi -i "sine=frequency=220:duration=1:sample_rate=44100" '
    '-c:a aac -b:a 96k "${out.path}"',
  );
  if (!ReturnCode.isSuccess(await session.getReturnCode())) {
    throw StateError('could not build the sample clip');
  }
  return out.readAsBytes();
}

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('every filter renders audio rather than failing', (tester) async {
    // Record a real clip through the processor's own encoder first: a
    // hand-rolled byte array is not an m4a, and the failure it produces would
    // be the fixture's, not the filter's.
    final source = await _sampleClip();
    expect(source, isNotEmpty, reason: 'no sample clip to work from');

    for (final filter in WhisperVoiceFilters.all) {
      if (filter == 'none') continue;
      final out = await WhisperVoiceProcessor.instance.process(
        sourceBytes: source,
        filter: filter,
      );
      expect(
        out,
        isNotEmpty,
        reason: '$filter produced no audio on a real device',
      );
      expect(
        out.length,
        greaterThan(200),
        reason: '$filter produced a file too small to be a clip',
      );
    }
  });

  testWidgets('the sheet opens, offers every voice, and sends one', (
    tester,
  ) async {
    final source = await _sampleClip();
    ComposedVoiceNote? sent;

    await tester.pumpWidget(
      MaterialApp(
        home: Builder(
          builder: (context) => Scaffold(
            body: Center(
              child: ElevatedButton(
                onPressed: () async {
                  sent = await showVoiceNoteComposer(
                    context,
                    recorded: source,
                    seconds: 1,
                  );
                },
                child: const Text('open'),
              ),
            ),
          ),
        ),
      ),
    );

    await tester.tap(find.text('open'));
    await tester.pumpAndSettle();

    for (final filter in WhisperVoiceFilters.all) {
      expect(
        find.byKey(ValueKey('vn-filter-$filter')),
        findsOneWidget,
        reason: '$filter is not offered',
      );
    }
    expect(find.byKey(const ValueKey('vn-send')), findsOneWidget);
    expect(find.byKey(const ValueKey('vn-preview')), findsOneWidget);

    // Pick a disguise, let it render, and send it.
    await tester.tap(find.byKey(const ValueKey('vn-filter-deep_voice')));
    await tester.pumpAndSettle(const Duration(seconds: 6));
    await tester.tap(find.byKey(const ValueKey('vn-send')));
    await tester.pumpAndSettle(const Duration(seconds: 6));

    expect(sent, isNotNull, reason: 'Send returned nothing');
    expect(sent!.seconds, 1);
    expect(
      sent!.bytes,
      isNot(equals(source)),
      reason: 'the bytes handed back are the original recording — the filter '
          'was never applied, and the real voice would have been uploaded',
    );
    expect(tester.takeException(), isNull);
  });

  testWidgets('dismissing it hands back nothing', (tester) async {
    final source = await _sampleClip();
    ComposedVoiceNote? sent;
    var returned = false;

    await tester.pumpWidget(
      MaterialApp(
        home: Builder(
          builder: (context) => Scaffold(
            body: Center(
              child: ElevatedButton(
                onPressed: () async {
                  sent = await showVoiceNoteComposer(
                    context,
                    recorded: source,
                    seconds: 1,
                  );
                  returned = true;
                },
                child: const Text('open'),
              ),
            ),
          ),
        ),
      ),
    );

    await tester.tap(find.text('open'));
    await tester.pumpAndSettle();
    Navigator.of(tester.element(find.byType(Scaffold).first)).pop();
    await tester.pumpAndSettle();

    expect(returned, isTrue);
    expect(sent, isNull, reason: 'a dismissed sheet must send nothing');
  });
}
